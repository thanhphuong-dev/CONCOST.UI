using System;
using System.Collections;
using System.Collections.Generic;
using System.ComponentModel;
using System.Runtime.CompilerServices;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Controls.Primitives;
using System.Windows.Data;
using System.Windows.Media;
using CONCOST.UI.Icons;

namespace CONCOST.UI.Controls;

/// <summary>
/// A <see cref="DataGrid"/> that shows a hierarchy: bind <see cref="RootItems"/> and the grid
/// flattens the tree into rows, one row per visible node.
/// </summary>
/// <remarks>
/// <para>
/// The rows are the items themselves, not wrappers, so every column keeps binding straight to the
/// item's properties — nothing has to be re-projected through a row view model.
/// </para>
/// <para>
/// The first column is generated by the grid: it draws the indent and the expander, and hosts the
/// item through <see cref="HierarchyContentTemplate"/>. Expansion state lives in the control and is
/// keyed by object reference, so it survives a rebuild of the flat list.
/// </para>
/// </remarks>
public class TreeDataGrid : DataGrid
{
    static TreeDataGrid()
    {
        DefaultStyleKeyProperty.OverrideMetadata(typeof(TreeDataGrid),
            new FrameworkPropertyMetadata(typeof(TreeDataGrid)));
    }

    private sealed class RowInfo
    {
        public int Level;
        public bool HasChildren;
    }

    /// <summary>Reference identity: two rows with equal values are still two different nodes.</summary>
    private sealed class ReferenceComparer : IEqualityComparer<object>
    {
        public static readonly ReferenceComparer Instance = new();

        public new bool Equals(object? x, object? y) => ReferenceEquals(x, y);

        public int GetHashCode(object obj) => RuntimeHelpers.GetHashCode(obj);
    }

    private readonly List<object> _rows = new();
    private readonly Dictionary<object, RowInfo> _info = new(ReferenceComparer.Instance);
    private readonly HashSet<object> _expanded = new(ReferenceComparer.Instance);
    private DataGridTemplateColumn? _hierarchyColumn;
    private bool _rebuilding;

    public TreeDataGrid()
    {
        LoadingRow += OnRowLoading;
        UnloadingRow += OnRowUnloading;
        ApplyHierarchyColumn();
    }

    // ---------------------------------------------------------------- hierarchy source

    public static readonly DependencyProperty RootItemsProperty =
        DependencyProperty.Register(nameof(RootItems), typeof(IEnumerable), typeof(TreeDataGrid),
            new PropertyMetadata(null, OnSourceChanged));

    /// <summary>The top-level nodes. Children are read through <see cref="ChildrenPath"/>.</summary>
    public IEnumerable? RootItems
    {
        get => (IEnumerable?)GetValue(RootItemsProperty);
        set => SetValue(RootItemsProperty, value);
    }

    public static readonly DependencyProperty ChildrenPathProperty =
        DependencyProperty.Register(nameof(ChildrenPath), typeof(string), typeof(TreeDataGrid),
            new PropertyMetadata("Children", OnSourceChanged));

    /// <summary>Property (or dotted path) that yields a node's children. Default <c>Children</c>.</summary>
    public string ChildrenPath
    {
        get => (string)GetValue(ChildrenPathProperty);
        set => SetValue(ChildrenPathProperty, value);
    }

    // ---------------------------------------------------------------- hierarchy column

    public static readonly DependencyProperty ShowHierarchyColumnProperty =
        DependencyProperty.Register(nameof(ShowHierarchyColumn), typeof(bool), typeof(TreeDataGrid),
            new PropertyMetadata(true, OnHierarchyColumnChanged));

    /// <summary>Draw the generated indent + expander column. Default <c>true</c>.</summary>
    public bool ShowHierarchyColumn
    {
        get => (bool)GetValue(ShowHierarchyColumnProperty);
        set => SetValue(ShowHierarchyColumnProperty, value);
    }

    public static readonly DependencyProperty HierarchyHeaderProperty =
        DependencyProperty.Register(nameof(HierarchyHeader), typeof(object), typeof(TreeDataGrid),
            new PropertyMetadata("Tên", OnHierarchyColumnChanged));

    /// <summary>Header of the generated column.</summary>
    public object? HierarchyHeader
    {
        get => GetValue(HierarchyHeaderProperty);
        set => SetValue(HierarchyHeaderProperty, value);
    }

    public static readonly DependencyProperty HierarchyColumnWidthProperty =
        DependencyProperty.Register(nameof(HierarchyColumnWidth), typeof(double), typeof(TreeDataGrid),
            new PropertyMetadata(260.0, OnHierarchyColumnChanged));

    /// <summary>Width of the generated column, in pixels. Default 260.</summary>
    public double HierarchyColumnWidth
    {
        get => (double)GetValue(HierarchyColumnWidthProperty);
        set => SetValue(HierarchyColumnWidthProperty, value);
    }

    public static readonly DependencyProperty IndentSizeProperty =
        DependencyProperty.Register(nameof(IndentSize), typeof(double), typeof(TreeDataGrid),
            new PropertyMetadata(18.0, OnIndentSizeChanged));

    /// <summary>Pixels added per nesting level. Default 18.</summary>
    public double IndentSize
    {
        get => (double)GetValue(IndentSizeProperty);
        set => SetValue(IndentSizeProperty, value);
    }

    public static readonly DependencyProperty HierarchyContentTemplateProperty =
        DependencyProperty.Register(nameof(HierarchyContentTemplate), typeof(DataTemplate), typeof(TreeDataGrid),
            new PropertyMetadata(null));

    /// <summary>Template for the item inside the generated column. Empty renders the item's text.</summary>
    public DataTemplate? HierarchyContentTemplate
    {
        get => (DataTemplate?)GetValue(HierarchyContentTemplateProperty);
        set => SetValue(HierarchyContentTemplateProperty, value);
    }

    public static readonly DependencyProperty HierarchyPathProperty =
        DependencyProperty.Register(nameof(HierarchyPath), typeof(string), typeof(TreeDataGrid),
            new PropertyMetadata(string.Empty, OnHierarchyPathChanged));

    /// <summary>
    /// Property (or dotted path) whose value is shown in the generated column, the way
    /// <see cref="System.Windows.Controls.ItemsControl.DisplayMemberPath"/> works. Without it the
    /// cell shows <see cref="object.ToString"/> of the node, which is rarely what a caller wants.
    /// </summary>
    public string HierarchyPath
    {
        get => (string)GetValue(HierarchyPathProperty);
        set => SetValue(HierarchyPathProperty, value);
    }

    private static readonly DependencyPropertyKey VisibleItemCountPropertyKey =
        DependencyProperty.RegisterReadOnly(nameof(VisibleItemCount), typeof(int), typeof(TreeDataGrid),
            new PropertyMetadata(0));

    public static readonly DependencyProperty VisibleItemCountProperty = VisibleItemCountPropertyKey.DependencyProperty;

    /// <summary>How many rows are currently visible (expanded branches only).</summary>
    public int VisibleItemCount => (int)GetValue(VisibleItemCountProperty);

    // ---------------------------------------------------------------- per-row attached state

    public static readonly DependencyProperty LevelProperty =
        DependencyProperty.RegisterAttached("Level", typeof(int), typeof(TreeDataGrid),
            new FrameworkPropertyMetadata(0));

    public static readonly DependencyProperty IndentWidthProperty =
        DependencyProperty.RegisterAttached("IndentWidth", typeof(double), typeof(TreeDataGrid),
            new FrameworkPropertyMetadata(0.0));

    public static readonly DependencyProperty HasChildrenProperty =
        DependencyProperty.RegisterAttached("HasChildren", typeof(bool), typeof(TreeDataGrid),
            new FrameworkPropertyMetadata(false));

    public static readonly DependencyProperty IsExpandedProperty =
        DependencyProperty.RegisterAttached("IsExpanded", typeof(bool), typeof(TreeDataGrid),
            new FrameworkPropertyMetadata(false, OnRowExpandedChanged));

    public static int GetLevel(DependencyObject element) => (int)element.GetValue(LevelProperty);

    public static double GetIndentWidth(DependencyObject element) => (double)element.GetValue(IndentWidthProperty);

    public static bool GetHasChildren(DependencyObject element) => (bool)element.GetValue(HasChildrenProperty);

    public static bool GetIsExpanded(DependencyObject element) => (bool)element.GetValue(IsExpandedProperty);

    public static void SetIsExpanded(DependencyObject element, bool value) => element.SetValue(IsExpandedProperty, value);

    // ---------------------------------------------------------------- public API

    /// <summary>Expands every branch that has children.</summary>
    public void ExpandAll()
    {
        WalkAll((item, hasChildren) =>
        {
            if (hasChildren) _expanded.Add(item);
        });
        Rebuild();
    }

    /// <summary>Collapses every branch, leaving only the roots visible.</summary>
    public void CollapseAll()
    {
        _expanded.Clear();
        Rebuild();
    }

    /// <summary>Expands the branch that leads to <paramref name="item"/>, then scrolls it into view.</summary>
    public void ExpandTo(object item)
    {
        if (item is null) return;

        var chain = new List<object>();
        if (FindPath(RootItems, item, chain))
        {
            for (int i = 0; i < chain.Count - 1; i++) _expanded.Add(chain[i]);
            Rebuild();
            ScrollIntoView(item);
        }
    }

    /// <summary>True when the node is expanded right now.</summary>
    public bool IsNodeExpanded(object item) => item is not null && _expanded.Contains(item);

    /// <summary>Flips one node between expanded and collapsed.</summary>
    public void ToggleNode(object item)
    {
        if (item is null) return;
        if (!_expanded.Remove(item)) _expanded.Add(item);
        Rebuild();
    }

    // ---------------------------------------------------------------- build

    private static void OnSourceChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is TreeDataGrid grid) grid.Rebuild();
    }

    private static void OnIndentSizeChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is not TreeDataGrid grid) return;
        foreach (var row in grid.FindRows()) grid.ApplyRowState(row);
    }

    private static void OnHierarchyColumnChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is TreeDataGrid grid) grid.ApplyHierarchyColumn();
    }

    private static void OnHierarchyPathChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is not TreeDataGrid grid) return;

        // The path is baked into the cell binding, so the column has to be rebuilt rather than
        // updated in place.
        if (grid._hierarchyColumn is not null)
        {
            grid.Columns.Remove(grid._hierarchyColumn);
            grid._hierarchyColumn = null;
        }

        grid.ApplyHierarchyColumn();
    }

    private void Rebuild()
    {
        if (_rebuilding) return;
        _rebuilding = true;
        try
        {
            _rows.Clear();
            _info.Clear();
            Walk(RootItems, 0);

            ItemsSource = null;
            ItemsSource = new List<object>(_rows);
            SetValue(VisibleItemCountPropertyKey, _rows.Count);
        }
        finally
        {
            _rebuilding = false;
        }
    }

    private void Walk(IEnumerable? nodes, int level)
    {
        if (nodes is null) return;

        foreach (var node in nodes)
        {
            if (node is null) continue;

            var children = GetChildren(node);
            bool hasChildren = HasAny(children);

            _rows.Add(node);
            _info[node] = new RowInfo { Level = level, HasChildren = hasChildren };

            if (hasChildren && _expanded.Contains(node)) Walk(children, level + 1);
        }
    }

    private IEnumerable? GetChildren(object item)
    {
        var path = ChildrenPath;
        if (string.IsNullOrEmpty(path)) return null;

        var descriptor = TypeDescriptor.GetProperties(item)[path];
        return descriptor?.GetValue(item) as IEnumerable;
    }

    private static bool HasAny(IEnumerable? items)
    {
        if (items is null) return false;
        foreach (var item in items)
        {
            if (item is not null) return true;
        }
        return false;
    }

    private void WalkAll(Action<object, bool> visit)
    {
        void WalkNode(IEnumerable? nodes)
        {
            if (nodes is null) return;
            foreach (var node in nodes)
            {
                if (node is null) continue;
                var children = GetChildren(node);
                bool hasChildren = HasAny(children);
                visit(node, hasChildren);
                if (hasChildren) WalkNode(children);
            }
        }

        WalkNode(RootItems);
    }

    private bool FindPath(IEnumerable? nodes, object target, List<object> chain)
    {
        if (nodes is null) return false;

        foreach (var node in nodes)
        {
            if (node is null) continue;

            chain.Add(node);
            if (ReferenceEquals(node, target)) return true;

            if (FindPath(GetChildren(node), target, chain)) return true;
            chain.RemoveAt(chain.Count - 1);
        }

        return false;
    }

    // ---------------------------------------------------------------- row state

    private void OnRowLoading(object? sender, DataGridRowEventArgs e) => ApplyRowState(e.Row);

    private void OnRowUnloading(object? sender, DataGridRowEventArgs e)
    {
        // The container is recycled; drop the values so a stale indent never leaks onto another row.
        e.Row.ClearValue(LevelProperty);
        e.Row.ClearValue(IndentWidthProperty);
        e.Row.ClearValue(HasChildrenProperty);
        e.Row.ClearValue(IsExpandedProperty);
    }

    private void ApplyRowState(DataGridRow row)
    {
        if (row.DataContext is not object item || !_info.TryGetValue(item, out var info)) return;

        row.SetValue(LevelProperty, info.Level);
        row.SetValue(IndentWidthProperty, info.Level * IndentSize);
        row.SetValue(HasChildrenProperty, info.HasChildren);

        // Written through the field: the change callback would rebuild the list we are filling.
        _rebuilding = true;
        try
        {
            row.SetValue(IsExpandedProperty, _expanded.Contains(item));
        }
        finally
        {
            _rebuilding = false;
        }
    }

    private IEnumerable<DataGridRow> FindRows()
    {
        for (int i = 0; i < Items.Count; i++)
        {
            if (ItemContainerGenerator.ContainerFromIndex(i) is DataGridRow row) yield return row;
        }
    }

    private static void OnRowExpandedChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is not DataGridRow row) return;

        var grid = FindOwner(row);
        if (grid is null || grid._rebuilding || row.DataContext is null) return;

        bool expanded = (bool)e.NewValue;
        if (expanded == grid._expanded.Contains(row.DataContext)) return;

        if (expanded) grid._expanded.Add(row.DataContext);
        else grid._expanded.Remove(row.DataContext);

        grid.Rebuild();
    }

    private static TreeDataGrid? FindOwner(DependencyObject start)
    {
        var current = start;
        while (current is not null)
        {
            if (current is TreeDataGrid grid) return grid;
            current = VisualTreeHelper.GetParent(current);
        }
        return null;
    }

    // ---------------------------------------------------------------- generated column

    private void ApplyHierarchyColumn()
    {
        if (ShowHierarchyColumn)
        {
            if (_hierarchyColumn is null)
            {
                _hierarchyColumn = BuildHierarchyColumn();
                Columns.Insert(0, _hierarchyColumn);
            }
            else
            {
                _hierarchyColumn.Header = HierarchyHeader;
                _hierarchyColumn.Width = new DataGridLength(HierarchyColumnWidth);
            }
        }
        else if (_hierarchyColumn is not null)
        {
            Columns.Remove(_hierarchyColumn);
            _hierarchyColumn = null;
        }
    }

    private static Style? _expanderStyle;

    /// <summary>
    /// The little chevron that opens a branch. Built here rather than in the theme because the
    /// generated column is created in code, and a theme lookup would not resolve before the
    /// control is in a tree.
    /// </summary>
    private static Style ExpanderStyle => _expanderStyle ??= BuildExpanderStyle();

    private static Style BuildExpanderStyle()
    {
        var chevron = new FrameworkElementFactory(typeof(Icon));
        chevron.SetValue(FrameworkElement.WidthProperty, 10.0);
        chevron.SetValue(FrameworkElement.HeightProperty, 10.0);
        chevron.SetValue(FrameworkElement.HorizontalAlignmentProperty, HorizontalAlignment.Center);
        chevron.SetValue(FrameworkElement.VerticalAlignmentProperty, VerticalAlignment.Center);
        chevron.SetBinding(Icon.KindProperty, new Binding(nameof(ToggleButton.IsChecked))
        {
            RelativeSource = new RelativeSource(RelativeSourceMode.TemplatedParent),
            Converter = ExpandedToChevronConverter.Instance
        });
        chevron.SetBinding(Control.ForegroundProperty, new Binding(nameof(Control.Foreground))
        {
            RelativeSource = new RelativeSource(RelativeSourceMode.TemplatedParent)
        });

        var border = new FrameworkElementFactory(typeof(Border));
        border.SetValue(Border.BackgroundProperty, Brushes.Transparent);
        border.SetValue(Border.CornerRadiusProperty, new CornerRadius(3));
        border.AppendChild(chevron);

        var style = new Style(typeof(ToggleButton));
        style.Setters.Add(new Setter(Control.TemplateProperty,
            new ControlTemplate(typeof(ToggleButton)) { VisualTree = border }));
        style.Setters.Add(new Setter(Control.FocusableProperty, false));
        style.Setters.Add(new Setter(Control.BackgroundProperty, Brushes.Transparent));
        style.Setters.Add(new Setter(Control.BorderThicknessProperty, new Thickness(0)));
        style.Setters.Add(new Setter(Control.PaddingProperty, new Thickness(0)));
        style.Setters.Add(new Setter(Control.ForegroundProperty,
            new DynamicResourceExtension("CONCOST.Brush.TextSecondary")));

        return style;
    }

    private DataGridTemplateColumn BuildHierarchyColumn()
    {
        var panel = new FrameworkElementFactory(typeof(StackPanel));
        panel.SetValue(StackPanel.OrientationProperty, Orientation.Horizontal);

        var indent = new FrameworkElementFactory(typeof(Border));
        indent.SetBinding(FrameworkElement.WidthProperty, new Binding
        {
            Path = new PropertyPath(IndentWidthProperty),
            RelativeSource = new RelativeSource(RelativeSourceMode.FindAncestor, typeof(DataGridRow), 1)
        });
        panel.AppendChild(indent);

        var toggle = new FrameworkElementFactory(typeof(ToggleButton));
        toggle.SetValue(FrameworkElement.WidthProperty, 18.0);
        toggle.SetValue(FrameworkElement.HeightProperty, 18.0);
        toggle.SetValue(FrameworkElement.MarginProperty, new Thickness(0, 0, 4, 0));
        toggle.SetValue(FrameworkElement.CursorProperty, System.Windows.Input.Cursors.Hand);
        toggle.SetValue(FrameworkElement.StyleProperty, ExpanderStyle);
        toggle.SetBinding(ToggleButton.IsCheckedProperty, new Binding
        {
            Path = new PropertyPath(IsExpandedProperty),
            Mode = BindingMode.TwoWay,
            RelativeSource = new RelativeSource(RelativeSourceMode.FindAncestor, typeof(DataGridRow), 1)
        });
        toggle.SetBinding(UIElement.VisibilityProperty, new Binding
        {
            Path = new PropertyPath(HasChildrenProperty),
            Converter = new BooleanToVisibilityConverter(),
            RelativeSource = new RelativeSource(RelativeSourceMode.FindAncestor, typeof(DataGridRow), 1)
        });
        panel.AppendChild(toggle);

        var content = new FrameworkElementFactory(typeof(ContentPresenter));
        content.SetValue(FrameworkElement.VerticalAlignmentProperty, VerticalAlignment.Center);

        var path = HierarchyPath;
        if (path is { Length: > 0 })
        {
            content.SetBinding(ContentPresenter.ContentProperty, new Binding(path));
        }
        else
        {
            content.SetBinding(ContentPresenter.ContentProperty, new Binding());
            content.SetBinding(ContentPresenter.ContentTemplateProperty, new Binding
            {
                Path = new PropertyPath(HierarchyContentTemplateProperty),
                RelativeSource = new RelativeSource(RelativeSourceMode.FindAncestor, typeof(TreeDataGrid), 1)
            });
        }
        panel.AppendChild(content);

        return new DataGridTemplateColumn
        {
            Header = HierarchyHeader,
            Width = new DataGridLength(HierarchyColumnWidth),
            CellTemplate = new DataTemplate { VisualTree = panel }
        };
    }

    /// <summary>Turns the row's expanded flag into the chevron glyph.</summary>
    private sealed class ExpandedToChevronConverter : IValueConverter
    {
        public static readonly ExpandedToChevronConverter Instance = new();

        public object Convert(object value, Type targetType, object parameter, System.Globalization.CultureInfo culture)
            => value is true ? IconKind.ChevronDown : IconKind.ChevronRight;

        public object ConvertBack(object value, Type targetType, object parameter, System.Globalization.CultureInfo culture)
            => Binding.DoNothing;
    }
}
