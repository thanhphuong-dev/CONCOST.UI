namespace CONCOST.UI.Controls.Ribbon;

/// <summary>How much room an item takes inside a <see cref="RibbonGroup"/>.</summary>
public enum RibbonItemSize
{
    /// <summary>Full column: 32 px icon above the label (3 rows tall).</summary>
    Large,

    /// <summary>Two rows: 20 px icon beside the label.</summary>
    Medium,

    /// <summary>One row: 16 px icon beside the label.</summary>
    Small
}
