namespace CONCOST.UI.Controls.Ribbon;

/// <summary>
/// Horizontal alignment of tabs inside the ribbon's tab strip.
/// </summary>
public enum RibbonTabAlignment
{
    /// <summary>Tabs start at the left edge, the default.</summary>
    Left,

    /// <summary>Tabs are centred in the available width.</summary>
    Center,

    /// <summary>Tabs are pushed to the right edge.</summary>
    Right
}
